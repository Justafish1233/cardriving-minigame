-- Run this once in the Supabase SQL Editor to create the shared player leaderboard.
create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 20),
  survival_seconds integer not null check (survival_seconds >= 0),
  coins integer not null check (coins >= 0),
  created_at timestamptz not null default now()
);

alter table public.leaderboard enable row level security;

revoke all on public.leaderboard from anon, authenticated;
grant select, insert on public.leaderboard to anon, authenticated;

drop policy if exists "Anyone can read leaderboard" on public.leaderboard;
create policy "Anyone can read leaderboard"
  on public.leaderboard for select to anon, authenticated using (true);

drop policy if exists "Anyone can submit a score" on public.leaderboard;
create policy "Anyone can submit a score"
  on public.leaderboard for insert to anon, authenticated with check (true);

grant usage, select on sequence public.leaderboard_id_seq to anon, authenticated;
